/**
 * weatherService.ts — Real-time weather & nature biome atmosphere adapter
 * backed by the Google Maps Platform Weather API (currentConditions:lookup).
 *
 * Features 32 interactive nature & botanical biome themes organized across
 * 6 natural categories. Automatically matches live Google Weather telemetry
 * (conditionType, temperatureC, relativeHumidity, windKmh, cloudCover,
 * isDaytime, and location latitude) to the most fitting nature biome, while
 * allowing instant interactive exploration of all 32 themes.
 */

