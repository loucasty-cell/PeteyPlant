export type NatureThemeCategory =
  | 'Solar & Clear'
  | 'Dawn & Golden'
  | 'Clouds & Breeze'
  | 'Rain & Monsoon'
  | 'Mist, Storm & Frost'
  | 'Nocturnal Biomes';

export type LandscapeArchetype =
  | 'rolling-meadow'
  | 'forest-canopy'
  | 'alpine-peaks'
  | 'coastal-lagoon'
  | 'desert-mesa'
  | 'botanical-arch';

export type SpecialSkyEffect =
  | 'none'
  | 'sunbeams'
  | 'rainbow'
  | 'aurora'
  | 'water-shimmer'
  | 'starlight'
  | 'blossoms';

export interface WeatherAtmosphereTheme {
  id: WeatherAtmosphereId;
  label: string;
  category: NatureThemeCategory;
  biomeSubtitle: string;
  landscape: LandscapeArchetype;
  specialEffect: SpecialSkyEffect;
  skyTop: string;
  skyMid: string;
  skyHorizon: string;
  hillFar: string;
  hillMid: string;
  hillNear: string;
  foliageSilhouette: string;
  groundTint: string;
  hudText: 'dark' | 'light';
  celestial: 'sun' | 'low-sun' | 'moon' | 'none';
  clouds: 'none' | 'light' | 'dense' | 'storm';
  particles: 'pollen' | 'rain' | 'storm-rain' | 'snow' | 'fireflies' | 'mist' | 'none';
  ambientColor: string;
  ambientIntensity: number;
  hemiSky: string;
  hemiGround: string;
  hemiIntensity: number;
  keyColor: string;
  keyIntensity: number;
  keyPosition: [number, number, number];
  rimColor: string;
  rimIntensity: number;
  fogColor: string;
  fogDensity: number;
  pedestalColor: string;
  pedestalAccent: string;
}

export interface LiveWeatherState {
  atmosphere: WeatherAtmosphereId;
  conditionLabel: string;
  conditionType: string | null;
  temperatureC: number | null;
  feelsLikeC: number | null;
  relativeHumidity: number | null;
  windKmh: number | null;
  cloudCover: number | null;
  uvIndex: number | null;
  isDaytime: boolean | null;
  locationLabel: string;
  source: 'google-weather' | 'preview';
  careContext: string;
  updatedAt: string | null;
}

export function formatWeatherReading(value: number | null, unit: string): string | null {
  return value === null ? null : `${value}${unit}`;
}

export interface WeatherLocationPreset {
  id: string;
  label: string;
  lat: number;
  lng: number;
  defaultBiome: WeatherAtmosphereId;
}

